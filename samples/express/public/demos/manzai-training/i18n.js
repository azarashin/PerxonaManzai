export function translate(language, key, parameters = {}) {
  const dictionary = dictionaries[language] ?? dictionaries.ja;
  const template = dictionary[key] ?? dictionaries.ja[key] ?? key;
  return Object.entries(parameters).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function applyTranslations(root, language) {
  const locale = { en: "en", zh: "zh-Hant", ja: "ja" }[language] ?? "ja";
  root.documentElement.lang = locale;

  for (const element of root.querySelectorAll("[data-i18n]")) {
    element.textContent = translate(language, element.dataset.i18n);
  }
  for (const element of root.querySelectorAll("[data-i18n-aria-label]")) {
    element.setAttribute(
      "aria-label",
      translate(language, element.dataset.i18nAriaLabel),
    );
  }
  for (const element of root.querySelectorAll("[data-i18n-content]")) {
    element.setAttribute(
      "content",
      translate(language, element.dataset.i18nContent),
    );
  }
}
